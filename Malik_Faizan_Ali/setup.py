#!/usr/bin/env python3
"""
SIOIS one-command backend setup (Windows / macOS / Linux). Uses only the Python standard library to start.

    python setup.py                      # interactive: asks for the PostgreSQL 'postgres' password
    python setup.py --pg-password XXXX   # non-interactive
    python setup.py --help

What it does (each step is skipped if already done, so it is safe to rerun):
  1. creates backend/.venv and installs backend/requirements.txt          (this replaces the stray *.whl files)
  2. creates the PostgreSQL user + databases (school_db, school_test_db)
  3. writes backend/.env with a fresh random JWT secret (never overwrites an existing .env unless --force-env)
  4. alembic upgrade head, then seeds: core, ops, attendance
  5. runs the test-suite (skip with --skip-tests)
Afterwards:  python check_system.py   (starts nothing; it calls the running API and prints a pass/fail table)
"""
from __future__ import annotations

import argparse
import getpass
import os
import re
import secrets
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BACKEND = ROOT / "backend"
VENV = BACKEND / ".venv"
IS_WIN = os.name == "nt"
VPY = VENV / ("Scripts/python.exe" if IS_WIN else "bin/python")


def say(msg: str) -> None:
    print(f"\n=== {msg}", flush=True)


def run(cmd: list[str], **kw) -> None:
    print("  $", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], check=True, **kw)


def ident(name: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
        sys.exit(f"Unsafe database/user name: {name!r} (letters, digits, underscore only)")
    return name


def make_venv() -> None:
    say("1/5 Python environment")
    if sys.version_info < (3, 11):
        sys.exit(f"Python 3.11+ required, you have {sys.version.split()[0]}")
    if not VPY.exists():
        run([sys.executable, "-m", "venv", VENV])
    run([VPY, "-m", "pip", "install", "--upgrade", "pip", "-q"])
    run([VPY, "-m", "pip", "install", "-r", BACKEND / "requirements.txt", "-q"])


DB_SNIPPET = r"""
import sys, psycopg2
from psycopg2 import sql
host, port, su, supw, appuser, apppw, *dbs = sys.argv[1:]
c = psycopg2.connect(host=host, port=int(port), user=su, password=supw or None, dbname="postgres")
c.autocommit = True
cur = c.cursor()
cur.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (appuser,))
if cur.fetchone():
    cur.execute(sql.SQL("ALTER ROLE {} WITH LOGIN PASSWORD %s").format(sql.Identifier(appuser)), (apppw,))
    print("  user exists, password synced:", appuser)
else:
    cur.execute(sql.SQL("CREATE ROLE {} WITH LOGIN PASSWORD %s").format(sql.Identifier(appuser)), (apppw,))
    print("  user created:", appuser)
for db in dbs:
    cur.execute("SELECT 1 FROM pg_database WHERE datname=%s", (db,))
    if cur.fetchone():
        print("  database exists:", db)
    else:
        cur.execute(sql.SQL("CREATE DATABASE {} OWNER {}").format(sql.Identifier(db), sql.Identifier(appuser)))
        print("  database created:", db)
"""


def make_db(a, app_pw: str) -> None:
    say("2/5 PostgreSQL user + databases")
    try:
        run([VPY, "-c", DB_SNIPPET, a.pg_host, str(a.pg_port), a.pg_user, a.pg_password,
             ident(a.db_user), app_pw, ident(a.db_name), ident(a.db_name + "_test")])
    except subprocess.CalledProcessError:
        sys.exit(
            "\nCould not create the database. Check that:\n"
            "  * PostgreSQL is installed and running (default port 5432)\n"
            f"  * the superuser '{a.pg_user}' password is right (--pg-password)\n"
            "Alternative: create them yourself (see docs/SETUP_GUIDE.md step 2) and rerun with --skip-db-create."
        )


def write_env(a, app_pw: str) -> None:
    say("3/5 backend/.env")
    env = BACKEND / ".env"
    if env.exists() and not a.force_env:
        print("  .env already exists - kept (use --force-env to rewrite it)")
        return
    base = f"postgresql+psycopg2://{a.db_user}:{app_pw}@{a.pg_host}:{a.pg_port}"
    env.write_text(
        "# Generated by setup.py. Never commit this file.\n"
        f"DATABASE_URL={base}/{a.db_name}\n"
        f"TEST_DATABASE_URL={base}/{a.db_name}_test\n"
        f"JWT_SECRET_KEY={secrets.token_urlsafe(48)}\n"
        "JWT_ACCESS_MINUTES=30\nJWT_REFRESH_DAYS=7\n"
        "CORS_ORIGINS=http://localhost:5000,http://127.0.0.1:5000,http://localhost:3000,http://localhost:8080\n"
        "APP_ENV=development\n"
        "# Demo passwords (FAKE data). Change both and set APP_ENV=production for real use.\n"
        "SEED_ADMIN_PASSWORD=Admin@12345\nSEED_USER_PASSWORD=School@12345\n"
        "UPLOAD_DIR=./uploads\nMAX_UPLOAD_MB=5\nFCM_ENABLED=false\nFCM_CREDENTIALS_FILE=\n",
        encoding="utf-8",
    )
    print("  written:", env)


def migrate_and_seed(a) -> None:
    say("4/5 Migrations + demo data")
    run([VPY, "-m", "alembic", "upgrade", "head"], cwd=BACKEND)
    for mod in ("seeds.seed_core", "seeds.seed_ops", "seeds.seed_attendance"):
        run([VPY, "-m", mod], cwd=BACKEND)


def tests() -> None:
    say("5/5 Backend tests (expect: 281 passed, 29 skipped)")
    run([VPY, "-m", "pytest"], cwd=BACKEND)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--pg-host", default="localhost")
    p.add_argument("--pg-port", type=int, default=5432)
    p.add_argument("--pg-user", default="postgres", help="PostgreSQL superuser used once to create the app user")
    p.add_argument("--pg-password", default=None, help="superuser password (prompted if omitted)")
    p.add_argument("--db-user", default="school_user")
    p.add_argument("--db-password", default=None, help="password for the app DB user (random if omitted)")
    p.add_argument("--db-name", default="school_db")
    p.add_argument("--skip-db-create", action="store_true")
    p.add_argument("--force-env", action="store_true")
    p.add_argument("--skip-tests", action="store_true")
    a = p.parse_args()

    make_venv()
    app_pw = a.db_password or secrets.token_urlsafe(18).replace("-", "x").replace("_", "y")
    if not a.skip_db_create:
        if a.pg_password is None:
            a.pg_password = getpass.getpass(f"PostgreSQL '{a.pg_user}' password (Enter if none): ")
        existing = BACKEND / ".env"
        if existing.exists() and not a.force_env and not a.db_password:
            # keep the password already in .env so a rerun does not break it
            m = re.search(r"DATABASE_URL=[^:]+://[^:]+:([^@]+)@", existing.read_text(encoding="utf-8"))
            if m:
                app_pw = m.group(1)
        make_db(a, app_pw)
    write_env(a, app_pw)
    migrate_and_seed(a)
    if not a.skip_tests:
        tests()
    say("DONE")
    print(
        "Start the API:\n"
        f"  {'start_backend.bat' if IS_WIN else './start_backend.sh'}\n"
        "Then, in a second terminal, prove it works:\n"
        "  python check_system.py\n"
        "Docs in the browser: http://localhost:8000/docs\n"
        "Logins: admin / Admin@12345   teacher1..10, student1..48, parent1..40 / School@12345"
    )


if __name__ == "__main__":
    main()
